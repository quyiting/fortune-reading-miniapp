const path = require("node:path");
const fs = require("node:fs");
const esbuild = require("esbuild");
const root = path.resolve(__dirname, "..");
for (const [entry, file] of [
  ["lunar-javascript", "lunar"],
  ["iztro", "iztro"],
]) {
  esbuild.buildSync({
    stdin: {
      contents: `module.exports = require(${JSON.stringify(require.resolve(entry))});`,
      resolveDir: root,
    },
    bundle: true,
    platform: "neutral",
    mainFields: ["main", "module"],
    format: "cjs",
    target: "es2017",
    minify: true,
    legalComments: "eof",
    outfile: path.join(root, "vendor", file + ".js"),
    banner: {
      js: `// Generated by scripts/build-vendors.cjs. Licenses: ../licenses/. Do not edit.`,
    },
  });
}
for (const name of ["lunar-javascript", "iztro", "lunar-lite", "i18next", "dayjs", "lunar-typescript", "@babel/runtime"]) {
  let dir;
  try {
    dir = path.dirname(require.resolve(name + "/package.json"));
  } catch (error) {
    if (error.code !== "ERR_PACKAGE_PATH_NOT_EXPORTED") throw error;
    dir = path.dirname(require.resolve(name));
    while (!fs.existsSync(path.join(dir, "LICENSE"))) {
      const parent = path.dirname(dir);
      if (parent === dir) throw new Error(`Missing license: ${name}`);
      dir = parent;
    }
  }
  fs.copyFileSync(
    path.join(dir, "LICENSE"),
    path.join(root, "licenses", name.replace("/", "-") + "-LICENSE"),
  );
}
